/* The console font: one table, both rings.
 *
 * WHY IT IS A HEADER AND NOT TWO ARRAYS. The kernel uploads this into the VGA
 * font plane at 0xA0000 and blits it into a linear framebuffer; console_server
 * blits the same glyphs once it owns the display. Two copies of a font are two
 * things that can disagree about what a character looks like, and the disagreement
 * is invisible until somebody reads a screen -- which is the failure mode this
 * tree already has a checker for in the .bin container (S80, eleven copies of one
 * format). One declaration, included by both.
 *
 * BIT 7 IS THE LEFTMOST PIXEL. That is not a convention chosen here: the VGA
 * hardware reads the font plane that way, so a blitter that disagreed would
 * mirror every glyph while the text console rendered correctly. It is asserted
 * by `make smoke-fb-console`, which checks PIXELS -- a mirrored blitter leaves
 * every serial line correct and the screen unreadable.
 *
 * PROVENANCE. This table has none, and that is recorded rather than glossed:
 * see THIRD_PARTY.md. It is ASCII-only, draws 7 pixels wide in an 8-pixel cell,
 * has no descenders, and its comma is a single pixel that reads as a full stop
 * on a framebuffer. Replacing it is planned and is blocked on the console's grid
 * becoming what the display can show rather than a fixed 80x50: at 8x16 an
 * 80x50 grid needs 800 lines and a 768-line panel -- which is what the target
 * hardware has -- gives 48 rows.
 *
 * `static` in a header, so each translation unit gets its own copy: 2 KiB twice
 * is not worth an extern and a definition site, and the alternative shares a
 * symbol across the ring boundary, which is not a thing this tree does. */
